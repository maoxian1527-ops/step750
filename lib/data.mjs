const SUBJECT_SHARE = { 物理类: 0.6, 历史类: 0.4 };

export function rankFromScore(score, provinceName, subject) {
  const prov = PROVINCES.find((p) => p.name === provinceName) || PROVINCES[0];
  const anchors = RANK_ANCHORS[subject] || RANK_ANCHORS['物理类'];
  const s = Math.max(0, Math.min(750, Number(score) || 0));
  const total = prov.candidates * (SUBJECT_SHARE[subject] || 0.6);

  if (s <= anchors[0][0]) {
    return Math.max(1, Math.round(total * 0.55));
  }
  const last = anchors[anchors.length - 1];
  if (s >= last[0]) {
    return Math.max(1, Math.round(total * last[1]));
  }
  for (let i = 0; i < anchors.length - 1; i += 1) {
    const [loScore, loFrac] = anchors[i];
    const [hiScore, hiFrac] = anchors[i + 1];
    if (s >= loScore && s <= hiScore) {
      const t = (s - loScore) / (hiScore - loScore);
      // 在对数空间插值，位次曲线更接近真实分布
      const frac = Math.exp(Math.log(loFrac) + t * (Math.log(hiFrac) - Math.log(loFrac)));
      return Math.max(1, Math.round(total * frac));
    }
  }
  return Math.max(1, Math.round(total * 0.5));
}

